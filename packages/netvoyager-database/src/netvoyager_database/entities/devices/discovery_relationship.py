
"""SQLAlchemy entity for discovery-candidate relationships."""

from __future__ import annotations

from typing import Any
from uuid import UUID

from sqlalchemy import (
    CheckConstraint,
    ForeignKey,
    JSON,
    String,
    UniqueConstraint,
    Uuid,
)
from sqlalchemy.orm import Mapped, mapped_column

from netvoyager_database.entities.base import Base, TimestampMixin


class DeviceDiscoveryRelationshipEntity(Base, TimestampMixin):
    """Persist an evidence-backed relationship between two candidates.

    Relationship identity is generated by the domain model.
    Supporting evidence is retained as UUID references.
    """

    __tablename__ = "device_discovery_relationships"

    __table_args__ = (
        CheckConstraint(
            "candidate_a_id != candidate_b_id",
            name="distinct_candidates",
        ),
        CheckConstraint(
            "status IN ('possible', 'confirmed', 'rejected')",
            name="valid_relationship_status",
        ),
        UniqueConstraint(
            "candidate_a_id",
            "candidate_b_id",
            name="unique_candidate_pair",
        ),
    )

    relationship_id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        primary_key=True,
    )

    candidate_a_id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("device_discovery_candidates.candidate_id"),
        nullable=False,
        index=True,
    )

    candidate_b_id: Mapped[UUID] = mapped_column(
        Uuid(as_uuid=True),
        ForeignKey("device_discovery_candidates.candidate_id"),
        nullable=False,
        index=True,
    )

    status: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
    )

    evidence_ids: Mapped[list[str]] = mapped_column(
        JSON,
        nullable=False,
        default=list,
    )
